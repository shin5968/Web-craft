import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {terrainFromOriginalStorage,meshVoxels} from '../web/voxel-data.mjs';
import {indexOf} from '../web/voxel-data.mjs';
import {createEditableTerrain,pickVoxel} from '../web/voxel-edit.mjs';
import assert from 'node:assert/strict';
const root=new URL('../web/minecraft-smoke/',import.meta.url);
const runtime=new URL('classes.wasm-runtime.js',root);
vm.runInThisContext(readFileSync(runtime,'utf8'),{filename:fileURLToPath(runtime)});
const app=await globalThis.TeaVM.wasmGC.load(new Uint8Array(readFileSync(new URL('classes.wasm',root))));
app.exports.main([]);
const mesh=meshVoxels(terrainFromOriginalStorage(app.exports));
if(!mesh.blocks||!mesh.faces)throw new Error('Empty test terrain');
console.log(`Original storage → mesh: 4096 values matched; ${mesh.blocks} blocks, ${mesh.faces} faces`);
const terrain=createEditableTerrain(app.exports);
const hit=pickVoxel(terrain.values,[.5,40,.5],[0,-1,0]);
assert.ok(hit);assert.deepEqual(hit.normal,[0,1,0]);
terrain.remove(hit);
assert.equal(terrain.values[indexOf(hit.x,hit.y,hit.z)],0);
assert.equal(meshVoxels(terrain.values).blocks,mesh.blocks-1);
const lower=pickVoxel(terrain.values,[.5,40,.5],[0,-1,0]);
assert.equal(lower.y,hit.y-1);
// Running another diagnostic must not overwrite scene edits.
app.exports.storageInit(1,1);
terrain.place(lower,3);
assert.equal(terrain.values[indexOf(hit.x,hit.y,hit.z)],3);
assert.equal(meshVoxels(terrain.values).blocks,mesh.blocks);
assert.equal(terrain.edits,2);
assert.throws(()=>terrain.place({x:0,y:0,z:0,normal:[-1,0,0]},1));
assert.throws(()=>terrain.place(lower,0));
terrain.reset();assert.equal(terrain.edits,0);
assert.equal(meshVoxels(terrain.values).blocks,mesh.blocks);
console.log('Original storage editing: remove, place, diagnostic isolation, bounds and reset passed');
