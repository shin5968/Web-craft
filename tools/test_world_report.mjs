import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {newWorldReport,fingerprint,recordFailure,sectionSummary} from '../web/world-report.mjs';
import {fixtureRegion} from './world-fixture.mjs';
const bytes=fixtureRegion(),report=newWorldReport({name:'sample.mca',size:bytes.length},{userAgent:'test'});
await fingerprint(report,bytes);
assert.equal(report.file.sha256,createHash('sha256').update(bytes).digest('hex'));
recordFailure(report,'read-file',new Error('Broken header'));
const json=JSON.parse(JSON.stringify(report));
assert.equal(json.schema,'web-craft.chunk-inspection.v1');
assert.equal(json.result.validation,'not-run');assert.equal(json.errors[0].stage,'read-file');
assert.ok(json.errors[0].message.includes('Broken header'));
const decoded={sectionY:-4,sourcePalette:['air','stone'],verified:4096,values:new Int32Array(4096),palette:{2:{name:'minecraft:stone',properties:{}}}};
decoded.values[1]=2;decoded.values[2]=2;
const summary=sectionSummary(decoded);
assert.equal(summary.air,4094);assert.equal(summary.nonAir,2);
assert.equal(summary.topStates[0].count,2);assert.equal(summary.usedNonAirStates,1);
assert.equal(summary.verifiedIndices,4096);assert.equal(summary.y,-4);
assert.equal(summary.raw,undefined);
